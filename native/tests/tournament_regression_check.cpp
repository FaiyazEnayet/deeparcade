namespace {

std::string read_file(const std::string& path) {
    std::ifstream in(path, std::ios::binary);
    if (!in) {
        throw std::runtime_error("cannot open " + path);
    }
    std::ostringstream contents;
    contents << in.rdbuf();
    return contents.str();
}

// ---- Minimal JSON reader ------------------------------------------------
// Objects, arrays, strings, numbers, booleans and null into a small
// DOM (the same approach as eval_regression_check's reader).

struct Json {
    enum class Type { Null, Bool, Number, String, Array, Object };
    Type type = Type::Null;
    std::string text;
    std::vector<Json> array;
    std::vector<std::pair<std::string, Json>> object;
    const Json* find(const std::string& key) const {
        if (type != Type::Object) return nullptr;
        for (const auto& m : object) {
            if (m.first == key) return &m.second;
        }
        return nullptr;
    }
};

class JsonParser {
public:
    explicit JsonParser(const std::string& text) : text_(text) {}
    Json parse() {
        Json value = parse_value();
        skip_ws();
        if (pos_ != text_.size()) fail("trailing characters");
        return value;
    }

private:
    const std::string& text_;
    std::size_t pos_ = 0;
    [[noreturn]] void fail(const std::string& what) const {
        throw std::runtime_error("JSON parse error at byte " +
                                 std::to_string(pos_) + ": " + what);
    }
    void skip_ws() {
        while (pos_ < text_.size()) {
            const char c = text_[pos_];
            if (c != ' ' && c != '\t' && c != '\n' && c != '\r') break;
            ++pos_;
        }
    }
    char peek() {
        if (pos_ >= text_.size()) fail("unexpected end of input");
        return text_[pos_];
    }
    bool consume(char c) {
        if (pos_ < text_.size() && text_[pos_] == c) {
            ++pos_;
            return true;
        }
        return false;
    }
    void expect(char c) {
        if (!consume(c)) fail(std::string("expected '") + c + "'");
    }
    void expect_literal(const char* literal) {
        const std::size_t len = std::strlen(literal);
        if (text_.compare(pos_, len, literal) != 0) fail("invalid literal");
        pos_ += len;
    }
    Json parse_value() {
        skip_ws();
        const char c = peek();
        if (c == '{') return parse_object();
        if (c == '[') return parse_array();
        Json value;
        if (c == '"') {
            value.type = Json::Type::String;
            value.text = parse_string();
        } else if (c == 't') {
            expect_literal("true");
            value.type = Json::Type::Bool;
            value.text = "true";
        } else if (c == 'f') {
            expect_literal("false");
            value.type = Json::Type::Bool;
            value.text = "false";
        } else if (c == 'n') {
            expect_literal("null");
            value.type = Json::Type::Null;
        } else {
            value.type = Json::Type::Number;
            value.text = parse_number();
        }
        return value;
    }
    Json parse_object() {
        Json value;
        value.type = Json::Type::Object;
        expect('{');
        skip_ws();
        if (consume('}')) return value;
        while (true) {
            skip_ws();
            if (peek() != '"') fail("expected a string object key");
            std::string key = parse_string();
            skip_ws();
            expect(':');
            value.object.emplace_back(std::move(key), parse_value());
            skip_ws();
            if (consume('}')) return value;
            expect(',');
        }
    }
    Json parse_array() {
        Json value;
        value.type = Json::Type::Array;
        expect('[');
        skip_ws();
        if (consume(']')) return value;
        while (true) {
            value.array.push_back(parse_value());
            skip_ws();
            if (consume(']')) return value;
            expect(',');
        }
    }
    void append_utf8(std::string& out, unsigned int cp) {
        if (cp < 0x80) {
            out += static_cast<char>(cp);
        } else if (cp < 0x800) {
            out += static_cast<char>(0xc0 | (cp >> 6));
            out += static_cast<char>(0x80 | (cp & 0x3f));
        } else if (cp < 0x10000) {
            out += static_cast<char>(0xe0 | (cp >> 12));
            out += static_cast<char>(0x80 | ((cp >> 6) & 0x3f));
            out += static_cast<char>(0x80 | (cp & 0x3f));
        } else {
            out += static_cast<char>(0xf0 | (cp >> 18));
            out += static_cast<char>(0x80 | ((cp >> 12) & 0x3f));
            out += static_cast<char>(0x80 | ((cp >> 6) & 0x3f));
            out += static_cast<char>(0x80 | (cp & 0x3f));
        }
    }
    unsigned int parse_hex4() {
        if (pos_ + 4 > text_.size()) fail("truncated \\u escape");
        unsigned int value = 0;
        for (int i = 0; i < 4; ++i) {
            const char c = text_[pos_++];
            value <<= 4;
            if (c >= '0' && c <= '9') value |= unsigned(c - '0');
            else if (c >= 'a' && c <= 'f') value |= unsigned(c - 'a' + 10);
            else if (c >= 'A' && c <= 'F') value |= unsigned(c - 'A' + 10);
            else fail("invalid hex digit in \\u escape");
        }
        return value;
    }
    std::string parse_string() {
        expect('"');
        std::string out;
        while (true) {
            if (pos_ >= text_.size()) fail("unterminated string");
            const char c = text_[pos_++];
            if (c == '"') return out;
            if (c != '\\') {
                out += c;
                continue;
            }
            if (pos_ >= text_.size()) fail("unterminated escape");
            switch (text_[pos_++]) {
                case '"': out += '"'; break;
                case '\\': out += '\\'; break;
                case '/': out += '/'; break;
                case 'b': out += '\b'; break;
                case 'f': out += '\f'; break;
                case 'n': out += '\n'; break;
                case 'r': out += '\r'; break;
                case 't': out += '\t'; break;
                case 'u': {
                    unsigned int cp = parse_hex4();
                    if (cp >= 0xd800 && cp <= 0xdbff &&
                        pos_ + 1 < text_.size() && text_[pos_] == '\\' &&
                        text_[pos_ + 1] == 'u') {
                        pos_ += 2;
                        const unsigned int lo = parse_hex4();
                        cp = 0x10000 + ((cp - 0xd800) << 10) +
                             (lo - 0xdc00);
                    }
                    append_utf8(out, cp);
                    break;
                }
                default: fail("invalid escape"); break;
            }
        }
    }
    std::string parse_number() {
        const std::size_t start = pos_;
        if (pos_ < text_.size() && text_[pos_] == '-') ++pos_;
        while (pos_ < text_.size()) {
            const char c = text_[pos_];
            if ((c >= '0' && c <= '9') || c == '.' || c == 'e' || c == 'E' ||
                c == '+' || c == '-') {
                ++pos_;
            } else {
                break;
            }
        }
        if (pos_ == start) fail("invalid number");
        return text_.substr(start, pos_ - start);
    }
};

// Checked member access in two forms: member() returns a pointer
// for call sites that keep the value (a reference bound from a call
// whose arguments include temporaries trips -Wdangling-reference),
// and req() returns a reference for immediate use.
const Json* member(const Json& object, const std::string& key,
                   const std::string& where) {
    const Json* value = object.find(key);
    if (value == nullptr) {
        throw std::runtime_error("eval file: missing " + where + "." + key);
    }
    return value;
}

const Json& req(const Json& object, const std::string& key,
                const std::string& where) {
    return *member(object, key, where);
}

std::int64_t as_int(const Json& value, const std::string& where) {
    if (value.type != Json::Type::Number) {
        throw std::runtime_error("eval file: " + where + " is not a number");
    }
    return std::stoll(value.text);
}

}  // namespace

int main(int argc, char** argv) {
    if (argc > 5) {
        std::cerr << "usage: tournament_regression_check [golden.json] "
                     "[qtable.json] [dqn_weights.json] [eval.json]\n";
        return 2;
    }
    const std::string golden_path =
        argc >= 2 ? argv[1] : "native/golden/tournament_standings.json";
    const std::string qtable_path = argc >= 3 ? argv[2] : "runs/qtable.json";
    const std::string weights_path =
        argc >= 4 ? argv[3] : "runs/dqn_weights.json";
    const std::string eval_path = argc >= 5 ? argv[4] : "runs/eval.json";

    const std::vector<std::string> kRoster = {"random", "greedy", "rookie",
                                              "pro", "grandmaster"};
    std::vector<std::string> failures;
    auto fail = [&failures](const std::string& msg) {
        failures.push_back(msg);
    };

    try {
        // ---- Frozen tournament ------------------------------------
        narcade::TournamentConfig config;
        config.rounds = 2;
        config.seeds_per_round = 2;
        config.seed0 = 5000;
        config.mcts_sims = 80;
        const auto qtable = narcade::load_qtable_json(qtable_path);
        const auto weights = narcade::load_dqn_weights(weights_path);
        std::vector<std::unique_ptr<narcade::Player>> players;
        for (const std::string& name : kRoster) {
            players.push_back(narcade::make_tournament_player(
                name, config.mcts_sims, &qtable, &weights));
        }
        const narcade::TournamentResult result =
            narcade::run_tournament(players, kRoster, config);
        const std::string report = narcade::tournament_report_json(result);
        const std::string golden = read_file(golden_path);
        const std::string golden_trimmed =
            golden.substr(0, golden.find_last_not_of(" \t\r\n") + 1);
        if (report == golden_trimmed) {
            std::cout << "frozen tournament: report byte-identical to "
                      << golden_path << '\n';
        } else {
            fail("frozen tournament report differs from " + golden_path +
                 " (regenerate it with the tournament CLI at the frozen "
                 "configuration if the change is intentional)");
        }

        // ---- Python reference artifact -----------------------------
        const Json doc = JsonParser(read_file(eval_path)).parse();
        const Json* paired = member(doc, "paired", "root");
        const Json* seeds_json = member(*paired, "seeds", "paired");
        const Json* scores_json = member(*paired, "scores", "paired");
        const Json* elo_json = member(doc, "elo", "root");
        std::vector<std::int64_t> seeds;
        for (const Json& s : seeds_json->array) {
            seeds.push_back(as_int(s, "paired.seeds"));
        }
        std::map<std::string, std::vector<int>> paired_scores;
        for (const std::string& name : kRoster) {
            const Json* arr = member(*scores_json, name, "paired.scores");
            for (const Json& v : arr->array) {
                paired_scores[name].push_back(
                    static_cast<int>(as_int(v, "paired.scores value")));
            }
            if (paired_scores[name].size() != seeds.size()) {
                fail("eval file: paired scores for " + name +
                     " do not cover the paired seeds");
            }
        }

        // Gate 2: episode spot parity for the four non-neural
        // players over the frozen tournament's seeds.
        {
            std::vector<std::int64_t> frozen_seeds;
            for (const auto& round : result.rounds) {
                for (const std::int64_t s : round.seeds) {
                    frozen_seeds.push_back(s);
                }
            }
            std::size_t compared = 0;
            for (std::size_t p = 0; p < kRoster.size(); ++p) {
                const std::string& name = kRoster[p];
                if (name == "pro") continue;
                std::vector<int> native_scores;
                for (const auto& round : result.rounds) {
                    for (const int s : round.scores[p].second) {
                        native_scores.push_back(s);
                    }
                }
                for (std::size_t i = 0; i < frozen_seeds.size(); ++i) {
                    const auto it = std::find(seeds.begin(), seeds.end(),
                                              frozen_seeds[i]);
                    if (it == seeds.end()) {
                        fail(name + ": frozen seed " +
                             std::to_string(frozen_seeds[i]) +
                             " is not in the eval file's paired seeds");
                        continue;
                    }
                    const std::size_t idx =
                        static_cast<std::size_t>(it - seeds.begin());
                    if (native_scores[i] != paired_scores[name][idx]) {
                        fail(name + " seed " +
                             std::to_string(frozen_seeds[i]) +
                             ": native score " +
                             std::to_string(native_scores[i]) +
                             " != eval.json paired score " +
                             std::to_string(paired_scores[name][idx]));
                    }
                    ++compared;
                }
            }
            std::cout << "episode spot parity: " << compared
                      << " non-neural episodes compared against "
                      << eval_path << '\n';
        }

        // Gate 3: Elo spot parity over the full paired pool.
        {
            narcade::OrderedResults aligned;
            for (const std::string& name : kRoster) {
                aligned.emplace_back(name, paired_scores[name]);
            }
            narcade::EloTable table(kRoster);
            narcade::play_score_block(table, aligned);
            const auto rounded = table.ratings_rounded();
            bool exact = true;
            for (std::size_t i = 0; i < kRoster.size(); ++i) {
                const std::int64_t want =
                    as_int(req(*elo_json, kRoster[i], "elo"), "elo value");
                if (rounded[i] != want) {
                    fail("elo parity " + kRoster[i] + ": native " +
                         std::to_string(rounded[i]) + " != eval.json " +
                         std::to_string(want));
                    exact = false;
                }
            }
            if (exact) {
                std::cout << "elo spot parity: native Elo over eval.json "
                             "paired scores reproduces its stored Elo "
                             "for all five players\n";
            }
        }

        if (!failures.empty()) {
            for (const std::string& failure : failures) {
                std::cout << "FAIL: " << failure << '\n';
            }
            std::cout << "result: FAIL\n";
            return 1;
        }
        std::cout << "result: PASS\n";
        return 0;
    } catch (const std::exception& error) {
        std::cerr << "tournament_regression_check: " << error.what() << '\n';
        return 1;
    }
}
