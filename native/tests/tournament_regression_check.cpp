// tournament_regression_check: frozen regression + Python spot
// parity for the native tournament runner, replayed in hosted CI.
//
// Three gates, all against committed files:
//
// 1. Frozen tournament. A small tournament (rounds=2,
//    seeds_per_round=2, seed0=5000, MCTS sims=80, all five players)
//    is run in-process and its rendered standings report is
//    byte-compared against native/golden/tournament_standings.json.
//    The golden stands outside meta.json's corpus accounting, like
//    eval_regression.json: meta_check and corpus_stats_check cover
//    the eight corpus files, and this file is none of those. It is
//    regenerated by running the tournament CLI at the frozen
//    configuration (narcade_tournament --rounds 2
//    --seeds-per-round 2 --seed0 5000 --sims 80 --out
//    native/golden/tournament_standings.json) and committing the
//    output together with any intentional protocol change.
//
// 2. Episode spot parity. The frozen tournament plays seeds
//    5000-5003 with single player instances in evaluate.py's order
//    and lifecycle, so for the four non-neural players its episode
//    scores must equal runs/eval.json's paired scores for those
//    seeds exactly (the same parity eval_regression freezes for
//    seeds 5000-5002). pro's episode scores are NOT compared: the
//    native forward pass is float32 with its own accumulation
//    order, so its episode outcomes are native results, gated for
//    action agreement by dqn_check, not for episode equality here.
//
// 3. Elo spot parity. runs/eval.json's paired scores for all five
//    players (50 seeds) are fed through the tournament Elo engine
//    in roster order; the rounded ratings must reproduce
//    runs/eval.json's stored Elo exactly. This is the protocol
//    parity claim for the shared Elo rules, pro included: the Elo
//    processing of scores is identical, even though pro's native
//    scores themselves are not claimed equal to Python's.
//
// Usage: tournament_regression_check [golden.json] [qtable.json]
//        [dqn_weights.json] [eval.json]
// Exit code is non-zero on any mismatch.
