// policies_diff_runner: batch differential-test endpoint for the C++
// policies and tabular Q-learning agent (CPP-02). The interactive
// protocol speaks with a driver that feeds inputs and checks replies;
// the fixture values come from native/golden/q_updates.json.
//
// Protocol (line-based text, stdin -> stdout). Doubles travel as 16
// lowercase hex digits holding the IEEE754 bit pattern (the encoding
// used by tools/native_reference.py and snake_diff_runner).
//
//   QUPDATES <alpha_hex> <gamma_hex> <epsilon_hex> <seed> <n>
//     then n lines:  U <s> <a> <r_hex> <s_next> <done>
//     replies: "QRESULT" then 32 lines of "<hex> <hex> <hex>".
//   QACT <seed> <epsilon_hex>
//     then: "QTABLE" + 32 table lines, "NSTATES <n>" + n state lines.
//     replies: "ACTIONS" then one line with the n actions.
//     (alpha/gamma take the Python class defaults 0.15/0.9, as in the
//     fixture's agent construction; they do not affect act().)
//   SETTABLE
//     then 32 table lines. Sets the runner's QTablePolicy table used by
//     BESTACTION and EPISODE. No reply.
//   BESTACTION
//     replies: "BEST" then one line with the 32 best actions.
//   RANDSEED <seed> <n>
//     replies: "RAND" then one line with n RandomPolicy actions.
//   EPISODE <width> <height> <seed> <max_steps|-1> <n_actions>
//     then n action lines (one integer each).
//     replies: "INIT <state> <food> <body>", then per action a line
//       "P <greedy> <qtable>"   ("P -1 -1" once the episode is done;
//                                policies are evaluated on the state
//                                BEFORE the step)
//       followed by the snake_diff_runner step line ("S ..." / "X ..."),
//     then "DONE".
//   <food> is "r,c" or "-1,-1"; <body> is "r,c" pairs joined by ';',
//   tail first; reason codes: 0 none, 1 death, 2 win, 3 timeout.
//
// Batch corpus mode: `policies_diff_runner <corpus-file>` replays a
// frozen session (native/golden/policies_corpus.txt, generated by
// tools/native_reference.py): lines starting "> " are fed in as
// interactive input, lines starting "< " are the expected replies.
// Every output field is compared; counts print and the exit code is
// non-zero on any mismatch or if the state threshold is unmet.
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <fstream>
#include <iostream>
#include <optional>
#include <sstream>
#include <stdexcept>
#include <string>
#include <vector>

#include "narcade/policies.hpp"
#include "narcade/qlearn.hpp"
#include "narcade/snake.hpp"

namespace {

std::string double_hex(double v) {
    std::uint64_t bits = 0;
    std::memcpy(&bits, &v, sizeof(bits));
    char buf[17];
    std::snprintf(buf, sizeof(buf), "%016llx",
                  static_cast<unsigned long long>(bits));
    return buf;
}

double parse_double_hex(const std::string& tok) {
    const std::uint64_t bits = std::stoull(tok, nullptr, 16);
    double v = 0.0;
    std::memcpy(&v, &bits, sizeof(v));
    return v;
}

std::string food_str(const std::optional<narcade::Cell>& food) {
    if (!food.has_value()) {
        return "-1,-1";
    }
    return std::to_string(food->r) + "," + std::to_string(food->c);
}

std::string body_str(const std::deque<narcade::Cell>& body) {
    std::string out;
    bool first = true;
    for (const narcade::Cell& cell : body) {
        if (!first) {
            out += ";";
        }
        first = false;
        out += std::to_string(cell.r) + "," + std::to_string(cell.c);
    }
    return out;
}

int reason_code(const std::optional<std::string>& reason) {
    if (!reason.has_value()) {
        return 0;
    }
    if (*reason == "death") {
        return 1;
    }
    if (*reason == "win") {
        return 2;
    }
    return 3;  // timeout
}

std::string join_ints(const std::vector<int>& values) {
    std::string out;
    bool first = true;
    for (int v : values) {
        if (!first) {
            out += ' ';
        }
        first = false;
        out += std::to_string(v);
    }
    return out;
}

// Reads 32 lines of "<hex> <hex> <hex>" into a 32x3 table.
narcade::QTablePolicy::Table read_table(std::istream& in) {
    narcade::QTablePolicy::Table table;
    std::string line;
    for (int s = 0; s < 32; ++s) {
        if (!std::getline(in, line)) {
            throw std::runtime_error("unexpected EOF in table");
        }
        std::istringstream row(line);
        std::string t0, t1, t2;
        row >> t0 >> t1 >> t2;
        table.push_back({parse_double_hex(t0), parse_double_hex(t1),
                         parse_double_hex(t2)});
    }
    return table;
}

void write_table(std::ostream& out,
                 const narcade::QLearningAgent::Table& table) {
    for (const std::vector<double>& row : table) {
        out << double_hex(row[0]) << ' ' << double_hex(row[1]) << ' '
            << double_hex(row[2]) << "\n";
    }
}

int run_stream(std::istream& in, std::ostream& out) {
    narcade::QTablePolicy current_table(
        narcade::QTablePolicy::Table(32, std::vector<double>(3, 0.0)));
    std::string line;
    while (std::getline(in, line)) {
        std::istringstream header(line);
        std::string tag;
        header >> tag;
        if (tag == "QUPDATES") {
            std::string alpha_hex, gamma_hex, epsilon_hex;
            std::int64_t seed = 0;
            int n = 0;
            header >> alpha_hex >> gamma_hex >> epsilon_hex >> seed >> n;
            narcade::QLearningAgent agent(
                32, 3, parse_double_hex(alpha_hex),
                parse_double_hex(gamma_hex), parse_double_hex(epsilon_hex),
                seed);
            for (int i = 0; i < n; ++i) {
                if (!std::getline(in, line)) {
                    return 1;
                }
                std::istringstream u(line);
                std::string utag, r_hex;
                int s = 0, a = 0, s_next = 0, done = 0;
                u >> utag >> s >> a >> r_hex >> s_next >> done;
                agent.update(s, a, parse_double_hex(r_hex), s_next,
                             done != 0);
            }
            out << "QRESULT\n";
            write_table(out, agent.q());
            out.flush();
        } else if (tag == "QACT") {
            std::string epsilon_hex;
            std::int64_t seed = 0;
            header >> seed >> epsilon_hex;
            if (!std::getline(in, line)) {  // "QTABLE"
                return 1;
            }
            const narcade::QLearningAgent::Table table = read_table(in);
            narcade::QLearningAgent agent(32, 3, 0.15, 0.9,
                                          parse_double_hex(epsilon_hex),
                                          seed);
            agent.set_q(table);
            if (!std::getline(in, line)) {  // "NSTATES <n>"
                return 1;
            }
            std::istringstream ns(line);
            std::string ntag;
            int n = 0;
            ns >> ntag >> n;
            std::vector<int> actions;
            for (int i = 0; i < n; ++i) {
                if (!std::getline(in, line)) {
                    return 1;
                }
                actions.push_back(agent.act(std::stoi(line)));
            }
            out << "ACTIONS\n" << join_ints(actions) << "\n";
            out.flush();
        } else if (tag == "SETTABLE") {
            current_table = narcade::QTablePolicy(read_table(in));
        } else if (tag == "BESTACTION") {
            out << "BEST\n" << join_ints(current_table.best_action())
                << "\n";
            out.flush();
        } else if (tag == "RANDSEED") {
            std::int64_t seed = 0;
            int n = 0;
            header >> seed >> n;
            narcade::RandomPolicy policy(seed);
            std::vector<int> actions;
            for (int i = 0; i < n; ++i) {
                actions.push_back(policy.act());
            }
            out << "RAND\n" << join_ints(actions) << "\n";
            out.flush();
        } else if (tag == "EPISODE") {
            int width = 0, height = 0, n_actions = 0;
            std::int64_t seed = 0, max_steps = -1;
            header >> width >> height >> seed >> max_steps >> n_actions;
            narcade::SnakeEnv env = max_steps >= 0
                ? narcade::SnakeEnv(width, height, seed, max_steps)
                : narcade::SnakeEnv(width, height, seed);
            out << "INIT " << env.encode_state() << ' '
                << food_str(env.food()) << ' ' << body_str(env.body())
                << "\n";
            for (int i = 0; i < n_actions; ++i) {
                if (!std::getline(in, line)) {
                    return 1;
                }
                const int action = std::stoi(line);
                if (env.done()) {
                    out << "P -1 -1\n";
                } else {
                    out << "P " << narcade::GreedyPolicy::act(env) << ' '
                        << current_table.act(env) << "\n";
                }
                const int state_before = env.encode_state();
                try {
                    const narcade::StepResult res = env.step(action);
                    out << "S " << state_before << ' ' << res.state << ' '
                        << double_hex(res.reward) << ' '
                        << (res.done ? 1 : 0) << ' '
                        << reason_code(res.reason) << ' '
                        << food_str(env.food()) << ' ' << env.score()
                        << ' ' << env.steps() << ' '
                        << body_str(env.body()) << "\n";
                } catch (const std::runtime_error&) {
                    out << "X runtime_error\n";
                } catch (const std::invalid_argument&) {
                    out << "X invalid_argument\n";
                }
            }
            out << "DONE\n";
            out.flush();
        }
        // Unknown lines are ignored, mirroring snake_diff_runner.
    }
    return 0;
}

std::vector<std::string> split_tokens(const std::string& line) {
    std::vector<std::string> toks;
    std::istringstream ss(line);
    std::string tok;
    while (ss >> tok) {
        toks.push_back(tok);
    }
    return toks;
}

int verify_corpus(const std::string& path) {
    std::ifstream file(path);
    if (!file) {
        std::cerr << "policies_diff_runner: cannot open corpus " << path
                  << "\n";
        return 1;
    }
    std::vector<std::string> inputs;
    std::vector<std::string> expected;
    std::vector<int> expected_line_no;
    std::string line;
    int lineno = 0;
    std::size_t updates = 0;
    while (std::getline(file, line)) {
        ++lineno;
        if (line.rfind("> ", 0) == 0) {
            inputs.push_back(line.substr(2));
            if (line.rfind("> U ", 0) == 0) {
                ++updates;
            }
        } else if (line.rfind("< ", 0) == 0) {
            expected.push_back(line.substr(2));
            expected_line_no.push_back(lineno);
        }
    }
    std::ostringstream script;
    for (const std::string& s : inputs) {
        script << s << '\n';
    }
    std::istringstream in(script.str());
    std::ostringstream captured;
    int rc = 0;
    try {
        rc = run_stream(in, captured);
    } catch (const std::exception& e) {
        std::cout << "corpus: runner raised: " << e.what() << "\n";
        std::cout << "result: FAIL\n";
        return 1;
    }
    std::vector<std::string> got;
    {
        std::istringstream out(captured.str());
        std::string l;
        while (std::getline(out, l)) {
            got.push_back(l);
        }
    }
    std::size_t episodes = 0;
    std::size_t states = 0;
    std::size_t exceptions = 0;
    std::size_t act_compared = 0;
    std::size_t rand_compared = 0;
    bool best_seen = false;
    const std::size_t n = std::min(got.size(), expected.size());
    for (std::size_t i = 0; i < n; ++i) {
        if (split_tokens(got[i]) != split_tokens(expected[i])) {
            std::cout << "corpus line " << expected_line_no[i]
                      << ": mismatch\n  expected: " << expected[i]
                      << "\n  runner:   " << got[i] << "\n";
            std::cout << "result: FAIL\n";
            return 1;
        }
        const std::string& e = expected[i];
        if (e.rfind("INIT ", 0) == 0) {
            ++episodes;
        } else if (e.rfind("P ", 0) == 0) {
            const std::vector<std::string> toks = split_tokens(e);
            if (toks.size() >= 3 && toks[1] != "-1") {
                ++states;
            }
        } else if (e.rfind("X ", 0) == 0) {
            ++exceptions;
        } else if (e == "ACTIONS" && i + 1 < n) {
            act_compared = split_tokens(expected[i + 1]).size();
        } else if (e == "RAND" && i + 1 < n) {
            rand_compared += split_tokens(expected[i + 1]).size();
        } else if (e == "BEST") {
            best_seen = true;
        }
    }
    if (rc != 0 || got.size() != expected.size()) {
        std::cout << "corpus: runner produced " << got.size()
                  << " output lines, expected " << expected.size()
                  << " (runner rc=" << rc << ")\n";
        std::cout << "result: FAIL\n";
        return 1;
    }
    std::cout << "fixture: updates replayed=" << updates
              << " act stream compared=" << act_compared
              << " best_action " << (best_seen ? "OK" : "MISSING")
              << ", RandomPolicy draws compared=" << rand_compared
              << "\n";
    std::cout << "corpus: episodes=" << episodes
              << " states compared=" << states << " (greedy " << states
              << ", qtable " << states << "), exceptions=" << exceptions
              << "\n";
    const bool ok = states >= 34532 && updates == 10000 &&
                    act_compared == 1000 && rand_compared == 10000 &&
                    best_seen;
    std::cout << "result: "
              << (ok ? "PASS" : "FAIL (coverage thresholds unmet)")
              << "\n";
    return ok ? 0 : 1;
}

}  // namespace

int main(int argc, char** argv) {
    std::ios::sync_with_stdio(false);
    if (argc >= 2) {
        return verify_corpus(argv[1]);
    }
    try {
        return run_stream(std::cin, std::cout);
    } catch (const std::exception&) {
        return 1;
    }
}
