// mcts_diff_runner: batch differential-test endpoint for the C++
// MCTSPlayer (CPP-03). The interactive protocol speaks with a driver
// that feeds states and checks replies; every compared value must
// agree with the Python reference.
//
// Protocol (line-based text, stdin -> stdout). Doubles travel as 16
// lowercase hex digits holding the IEEE754 bit pattern.
//
//   PLAYER <simulations> <rollout_steps> <c_hex> <seed>
//     Replaces the runner's persistent MCTSPlayer (its RNG state
//     carries across SEARCH calls, like the Python lifecycle).
//     Replies "OK".
//   ENV <width> <height> <seed>
//     Creates the runner's persistent SnakeEnv (default max_steps).
//     Replies "INIT <state> <food> <body>".
//   SEARCH
//     Searches the persistent env's current state with the
//     persistent player. Replies "ACTION <a>", "ROOT <k>", then k
//     lines "CHILD <action> <visits> <value_hex>" in insertion order.
//   STEP <action>
//     Steps the persistent env. Replies the snake S/X line:
//       "S <state_before> <state_after> <reward_hex> <done> <reason>
//        <food> <score> <steps> <body>" or "X runtime_error" /
//        "X invalid_argument".
//   SEARCHSTATE <w> <h> <food_r> <food_c> <heading> <n_body>
//     then n_body lines "<r> <c>" (tail first). One-shot search on
//     the serialized state with the persistent player; replies
//     ACTION/ROOT/CHILD lines as for SEARCH.
//   WALLS <n_walls>
//     then n_walls lines "<r> <c>". Replaces the runner's persistent
//     wall set (the maze-mode overlay MCTSPlayer.search receives);
//     SEARCH and SEARCHSTATE use it until the next WALLS command.
//     WALLS 0 clears it. Replies "OK".
//   <food> is "r,c" or "-1,-1"; <body> is "r,c" pairs joined by ';',
//   tail first; reason codes: 0 none, 1 death, 2 win, 3 timeout.
//
// Batch corpus mode: `mcts_diff_runner <cases-file> [min-searches]
// [min-root-children]` replays a frozen session (native/golden/
// mcts_cases.txt or native/golden/mcts_wall_cases.txt, generated by
// tools/native_reference.py): lines starting "> " are fed in as
// interactive input, lines starting "< " are the expected replies.
// Every output field is compared; counts print and the exit code is
// non-zero on any mismatch or if the search threshold is unmet. The
// thresholds default to the mcts_cases.txt corpus scale (1000 / 100).
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <deque>
#include <fstream>
#include <iostream>
#include <optional>
#include <sstream>
#include <stdexcept>
#include <string>
#include <vector>

#include "narcade/mcts.hpp"
#include "narcade/snake.hpp"

namespace {

std::string double_hex(double v) {
    std::uint64_t bits = 0;
    std::memcpy(&bits, &v, sizeof(bits));
    char buf[17];
    std::snprintf(buf, sizeof(buf), "%016llx",
                  static_cast<unsigned long long>(bits));
    return buf;
}

double parse_double_hex(const std::string& tok) {
    const std::uint64_t bits = std::stoull(tok, nullptr, 16);
    double v = 0.0;
    std::memcpy(&v, &bits, sizeof(v));
    return v;
}

std::string food_str(const std::optional<narcade::Cell>& food) {
    if (!food.has_value()) {
        return "-1,-1";
    }
    return std::to_string(food->r) + "," + std::to_string(food->c);
}

template <typename Container>
std::string body_str(const Container& body) {
    std::string out;
    bool first = true;
    for (const narcade::Cell& cell : body) {
        if (!first) {
            out += ";";
        }
        first = false;
        out += std::to_string(cell.r) + "," + std::to_string(cell.c);
    }
    return out;
}

int reason_code(const std::optional<std::string>& reason) {
    if (!reason.has_value()) {
        return 0;
    }
    if (*reason == "death") {
        return 1;
    }
    if (*reason == "win") {
        return 2;
    }
    return 3;  // timeout
}

void write_search_result(std::ostream& out,
                         const narcade::MctsSearchResult& res) {
    out << "ACTION " << res.action << "\n";
    out << "ROOT " << res.root_children.size() << "\n";
    for (const narcade::MctsRootChild& ch : res.root_children) {
        out << "CHILD " << ch.action << ' ' << ch.visits << ' '
            << double_hex(ch.value) << "\n";
    }
    out.flush();
}

narcade::MctsState env_state(const narcade::SnakeEnv& env) {
    narcade::MctsState state;
    state.width = env.width();
    state.height = env.height();
    state.body.assign(env.body().begin(), env.body().end());
    // A live env always has food unless the board is full (terminal
    // win); search on such a state is outside the Python contract
    // (it would index None), so map it to the (-1,-1) sentinel.
    state.food = env.food().value_or(narcade::Cell{-1, -1});
    state.heading = env.heading();
    return state;
}

int run_stream(std::istream& in, std::ostream& out) {
    std::optional<narcade::MCTSPlayer> player;
    std::optional<narcade::SnakeEnv> env;
    narcade::MctsWalls walls;
    std::string line;
    while (std::getline(in, line)) {
        std::istringstream header(line);
        std::string tag;
        header >> tag;
        if (tag == "PLAYER") {
            int simulations = 0, rollout_steps = 0;
            std::string c_hex;
            std::int64_t seed = 0;
            header >> simulations >> rollout_steps >> c_hex >> seed;
            player.emplace(simulations, rollout_steps,
                           parse_double_hex(c_hex), seed);
            out << "OK\n";
            out.flush();
        } else if (tag == "ENV") {
            int width = 0, height = 0;
            std::int64_t seed = 0;
            header >> width >> height >> seed;
            env.emplace(width, height, seed);
            out << "INIT " << env->encode_state() << ' '
                << food_str(env->food()) << ' '
                << body_str(env->body()) << "\n";
            out.flush();
        } else if (tag == "WALLS") {
            int n_walls = 0;
            header >> n_walls;
            walls.clear();
            for (int i = 0; i < n_walls; ++i) {
                if (!std::getline(in, line)) {
                    return 1;
                }
                std::istringstream cell_line(line);
                int r = 0, c = 0;
                cell_line >> r >> c;
                walls.insert(narcade::mcts_cell_key(r, c));
            }
            out << "OK\n";
            out.flush();
        } else if (tag == "SEARCH") {
            if (!player.has_value() || !env.has_value()) {
                return 1;
            }
            write_search_result(
                out, player->search_with_stats(env_state(*env), walls));
        } else if (tag == "STEP") {
            if (!env.has_value()) {
                return 1;
            }
            int action = 0;
            header >> action;
            const int state_before = env->encode_state();
            try {
                const narcade::StepResult res = env->step(action);
                out << "S " << state_before << ' ' << res.state << ' '
                    << double_hex(res.reward) << ' '
                    << (res.done ? 1 : 0) << ' '
                    << reason_code(res.reason) << ' '
                    << food_str(env->food()) << ' ' << env->score() << ' '
                    << env->steps() << ' ' << body_str(env->body())
                    << "\n";
            } catch (const std::runtime_error&) {
                out << "X runtime_error\n";
            } catch (const std::invalid_argument&) {
                out << "X invalid_argument\n";
            }
            out.flush();
        } else if (tag == "SEARCHSTATE") {
            if (!player.has_value()) {
                return 1;
            }
            narcade::MctsState state;
            int fr = -1, fc = -1, n_body = 0;
            header >> state.width >> state.height >> fr >> fc >>
                state.heading >> n_body;
            state.food = narcade::Cell{fr, fc};
            for (int i = 0; i < n_body; ++i) {
                if (!std::getline(in, line)) {
                    return 1;
                }
                std::istringstream cell_line(line);
                narcade::Cell cell;
                cell_line >> cell.r >> cell.c;
                state.body.push_back(cell);
            }
            write_search_result(
                out, player->search_with_stats(state, walls));
        }
        // Unknown lines are ignored, mirroring the other runners.
    }
    return 0;
}

std::vector<std::string> split_tokens(const std::string& line) {
    std::vector<std::string> toks;
    std::istringstream ss(line);
    std::string tok;
    while (ss >> tok) {
        toks.push_back(tok);
    }
    return toks;
}

int verify_corpus(const std::string& path, std::size_t min_searches,
                  std::size_t min_root_children) {
    std::ifstream file(path);
    if (!file) {
        std::cerr << "mcts_diff_runner: cannot open cases file " << path
                  << "\n";
        return 1;
    }
    std::vector<std::string> inputs;
    std::vector<std::string> expected;
    std::vector<int> expected_line_no;
    std::string line;
    int lineno = 0;
    while (std::getline(file, line)) {
        ++lineno;
        if (line.rfind("> ", 0) == 0) {
            inputs.push_back(line.substr(2));
        } else if (line.rfind("< ", 0) == 0) {
            expected.push_back(line.substr(2));
            expected_line_no.push_back(lineno);
        }
    }
    std::ostringstream script;
    for (const std::string& s : inputs) {
        script << s << '\n';
    }
    std::istringstream in(script.str());
    std::ostringstream captured;
    int rc = 0;
    try {
        rc = run_stream(in, captured);
    } catch (const std::exception& e) {
        std::cout << "corpus: runner raised: " << e.what() << "\n";
        std::cout << "result: FAIL\n";
        return 1;
    }
    std::vector<std::string> got;
    {
        std::istringstream out(captured.str());
        std::string l;
        while (std::getline(out, l)) {
            got.push_back(l);
        }
    }
    std::size_t searches = 0;
    std::size_t root_children = 0;
    const std::size_t n = std::min(got.size(), expected.size());
    for (std::size_t i = 0; i < n; ++i) {
        if (split_tokens(got[i]) != split_tokens(expected[i])) {
            std::cout << "corpus line " << expected_line_no[i]
                      << ": mismatch\n  expected: " << expected[i]
                      << "\n  runner:   " << got[i] << "\n";
            std::cout << "result: FAIL\n";
            return 1;
        }
        const std::string& e = expected[i];
        if (e.rfind("ACTION ", 0) == 0) {
            ++searches;
        } else if (e.rfind("CHILD ", 0) == 0) {
            ++root_children;
        }
    }
    if (rc != 0 || got.size() != expected.size()) {
        std::cout << "corpus: runner produced " << got.size()
                  << " output lines, expected " << expected.size()
                  << " (runner rc=" << rc << ")\n";
        std::cout << "result: FAIL\n";
        return 1;
    }
    std::cout << "corpus: searches compared=" << searches
              << " exact actions, root children compared="
              << root_children << " (bitexact)\n";
    const bool ok = searches >= min_searches &&
                    root_children >= min_root_children;
    std::cout << "result: "
              << (ok ? "PASS" : "FAIL (search threshold unmet)") << "\n";
    return ok ? 0 : 1;
}

}  // namespace

int main(int argc, char** argv) {
    std::ios::sync_with_stdio(false);
    if (argc >= 2) {
        const std::size_t min_searches =
            argc >= 3 ? std::stoul(argv[2]) : 1000;
        const std::size_t min_root_children =
            argc >= 4 ? std::stoul(argv[3]) : 100;
        return verify_corpus(argv[1], min_searches, min_root_children);
    }
    return run_stream(std::cin, std::cout);
}
