#!/usr/bin/env python3
"""Differential driver: C++ CNN DQN inference vs the Python reference.

Three modes:

  live (default)  Requires a Python with torch. The reference is the
    genuine DA8 CNN: narcade.models.load_cnn_checkpoint loads each
    committed export and the CNNDQN forward pass runs in PyTorch over
    encodings from narcade.models.encode_cnn_dqn itself; the NumPy
    mirror (narcade.models.cnn_logits_numpy, the checkpoint format's
    declared parity path) is computed alongside and reported.
    Comparisons (all reported, nothing hidden):
      encodings   bit-identical on every state (gate: 0 mismatches)
      actions     native argmax vs torch argmax. A disagreement with
                  reference Q-margin above 1e-5 (MARGIN_BAND) fails
                  the gate; near-tie disagreements inside the band
                  are reported as warnings.
      logits      two comparisons. Against the NumPy mirror (the
                  checkpoint format's declared parity path, sharing
                  the native float64 accumulation order): gate at
                  1e-5 (LOGIT_BAND, the band the MLP port is held
                  to); the observed difference sits at the float32
                  wire-cast level. Against PyTorch: reported, with
                  the mirror's own PyTorch difference alongside.
                  On the trained checkpoints the PyTorch float32
                  forward itself deviates from the float64 result
                  by 8.6e-6 to 1.8e-5 on this harvest (the mirror
                  shows the same deviation, printed alongside), so
                  no faithful float64 port can sit within 1e-5 of
                  PyTorch on all of them; the DA8 test suite's
                  sub-1e-5 mirror figure was measured on a randomly
                  initialized network over five inputs.
      features    pooled features + heading (the head1 input) on the
                  first --feat-subset states (reported, not gated)

  --frozen FIXTURE  No torch or numpy needed (stdlib only). Replays
    the states frozen in the fixture (default
    native/golden/cnn_parity.json) through the runner and gates on
    exact action agreement and a max logit difference of LOGIT_BAND
    against the fixture's recorded reference logits. The frozen
    reference is the NumPy mirror (the checkpoint format's declared
    parity path): it is deterministic float64 math, so the fixture
    is stable across platforms, unlike the PyTorch float32 forward
    whose accumulation error on the trained residual checkpoints
    reaches ~1.8e-5 (see the live mode notes). Agreement with
    PyTorch is established by the live check. This mode is the
    hosted-CI guard.

  --freeze PATH  Requires torch. Regenerates the fixture: harvests
    states, computes the NumPy-mirror reference for the two fixture
    checkpoints, and writes the fixture JSON. Freezing is a manual
    step; the frozen file is committed and is never regenerated by
    the test suite.

Harvest: the same deterministic harvest as tools/native_dqn_check.py
(>= --states states recorded before every step of seeded 12x12
SnakeEnv episodes, rotating greedy / random / qtable policies by
episode, seeds fixed).

Protocol with the runner is line-based text; see
native/tests/cnn_diff_runner.cpp. Floats travel as IEEE754 binary32
hex bit patterns.

Exit code is non-zero if a gate fails.
"""
from __future__ import annotations

import argparse
import json
import math
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "src"))

MARGIN_BAND = 1e-5
LOGIT_BAND = 1e-5

CHECKPOINTS = [
    "cnn_dqn_plain_seed7_weights.json",
    "cnn_dqn_plain_seed8_weights.json",
    "cnn_dqn_plain_seed9_weights.json",
    "cnn_dqn_residual_seed7_weights.json",
    "cnn_dqn_residual_seed8_weights.json",
    "cnn_dqn_residual_seed9_weights.json",
]
FIXTURE_CHECKPOINTS = [
    "cnn_dqn_plain_seed7_weights.json",
    "cnn_dqn_residual_seed7_weights.json",
]


def f32_from_hex(tok: str):
    return struct.unpack("<f", struct.pack("<I", int(tok, 16)))[0]


def f32_hex(value) -> str:
    """8 lowercase hex digits of the IEEE754 binary32 bit pattern,
    the same rendering the runner uses on the wire."""
    bits = struct.unpack("<I", struct.pack("<f", float(value)))[0]
    return f"{bits:08x}"


class Runner:
    """Line-protocol client for cnn_diff_runner."""

    def __init__(self, path: str):
        self.proc = subprocess.Popen([path], stdin=subprocess.PIPE,
                                     stdout=subprocess.PIPE, text=True)

    def send(self, line: str) -> None:
        self.proc.stdin.write(line + "\n")

    def recv(self) -> str:
        line = self.proc.stdout.readline()
        if not line:
            raise RuntimeError("runner closed stdout unexpectedly")
        return line.strip()

    def load(self, weights: str) -> None:
        self.send(f"LOAD {weights}")
        self.proc.stdin.flush()
        reply = self.recv()
        if reply != "OK":
            raise RuntimeError(f"runner LOAD replied: {reply}")

    def state(self, mode: int, body, food, heading):
        """Returns (enc_hex list, action, logits list, feat list|None)."""
        fr, fc = food if food is not None else (-1, -1)
        self.send(f"STATE {mode} {fr} {fc} {heading} {len(body)}")
        for r, c in body:
            self.send(f"{r} {c}")
        self.proc.stdin.flush()
        enc_line = self.recv().split()
        if enc_line[0] != "ENC" or len(enc_line) != 1 + 436:
            raise RuntimeError(
                f"bad ENC reply ({enc_line[0]}, {len(enc_line)} tokens)")
        out_line = self.recv().split()
        if out_line[0] != "OUT" or len(out_line) != 5:
            raise RuntimeError("bad OUT reply")
        feat = None
        if mode == 1:
            feat_line = self.recv().split()
            if feat_line[0] != "FEAT":
                raise RuntimeError("bad FEAT reply")
            feat = [f32_from_hex(t) for t in feat_line[2:]]
        return (enc_line[1:], int(out_line[1]),
                [f32_from_hex(t) for t in out_line[2:5]], feat)

    def close(self) -> None:
        self.proc.stdin.close()
        self.proc.wait(timeout=60)


def harvest(target: int):
    """Deterministic state harvest; returns [(body, food, heading)].

    Identical to tools/native_dqn_check.py's harvest (same seeds and
    policy rotation), so the two checks cover the same state stream.
    """
    import numpy as np  # noqa: F401  (kept for parity of environment)
    from narcade.policies import GreedyPolicy, QTablePolicy, RandomPolicy
    from narcade.snake import SnakeEnv

    with open(ROOT / "runs" / "qtable.json") as f:
        qtable = json.load(f)
    policies = [GreedyPolicy(), RandomPolicy(seed=777), QTablePolicy(qtable)]
    states = []
    ep = 0
    while len(states) < target and ep < 100000:
        env = SnakeEnv(width=12, height=12, seed=5000 + ep)
        env.reset()
        pol = policies[ep % 3]
        if isinstance(pol, RandomPolicy):
            pol = RandomPolicy(seed=777 + ep)
        done = False
        while not done:
            states.append((list(env.body), env.food, env.heading))
            _, _, done, _ = env.step(pol.act(env))
        ep += 1
    return states


def assess(enc_mismatch, action_disagree, max_mirror_diff):
    """Pure pass/fail decision over the live checker's gates.

    Mirrors tools/native_dqn_check.py's assess(): zero encoding
    mismatches; no action disagreement whose reference Q-margin
    exceeds MARGIN_BAND; the max logit difference against the NumPy
    mirror (the same-regime comparison) finite and within
    LOGIT_BAND.
    """
    reasons = []
    if enc_mismatch > 0:
        reasons.append(f"{enc_mismatch} encoding mismatch(es)")
    wide = [d for d in action_disagree if d[3] > MARGIN_BAND]
    if wide:
        reasons.append(
            f"{len(wide)} action disagreement(s) with reference "
            f"margin above the {MARGIN_BAND:.0e} margin band")
    if not math.isfinite(max_mirror_diff):
        reasons.append(
            f"max mirror logit difference {max_mirror_diff} is not "
            "finite")
    elif max_mirror_diff > LOGIT_BAND:
        reasons.append(
            f"max mirror logit difference {max_mirror_diff:.3e} "
            f"exceeds the {LOGIT_BAND:.0e} logit band")
    return bool(reasons), reasons


def torch_reference(weights_path: Path, states):
    """PyTorch logits, NumPy-mirror logits, encodings, features."""
    import numpy as np
    import torch
    import torch.nn.functional as F
    from types import SimpleNamespace

    from narcade.models import (cnn_logits_numpy, encode_cnn_dqn,
                                load_cnn_checkpoint)

    net, _info = load_cnn_checkpoint(str(weights_path))
    with open(weights_path) as f:
        doc = json.load(f)
    spatial = []
    heading = []
    for body, food, h in states:
        s, hd = encode_cnn_dqn(SimpleNamespace(
            width=12, height=12, body=list(body), food=food, heading=h))
        spatial.append(s)
        heading.append(hd)
    spatial = np.stack(spatial)
    heading = np.stack(heading)
    with torch.no_grad():
        x = torch.from_numpy(spatial)
        for conv in net.convs:
            x = F.relu(conv(x))
        if net.res1 is not None:
            r = F.relu(net.res1(x))
            r = net.res2(r)
            x = F.relu(x + r)
        x = F.adaptive_avg_pool2d(
            x, (net.config.pool_size, net.config.pool_size))
        feats = torch.cat([torch.flatten(x, start_dim=1),
                           torch.from_numpy(heading)], dim=1)
        logits = net.head2(F.relu(net.head1(feats))).numpy()
    mirror = cnn_logits_numpy(doc, spatial, heading)
    enc = np.concatenate([spatial.reshape(len(states), -1), heading],
                         axis=1)
    return logits, mirror, enc, feats.numpy()


def run_live(runner_path: str, weights_path: Path, states,
             feat_subset: int):
    import numpy as np

    logits, mirror, enc, feats = torch_reference(weights_path, states)
    n = len(states)
    ref_actions = logits.argmax(axis=1)
    top2 = np.partition(logits, -2, axis=1)
    margins = top2[:, -1] - top2[:, -2]
    enc_bits_ref = enc.view(np.uint32)

    runner = Runner(runner_path)
    runner.load(str(weights_path))
    enc_mismatch = 0
    action_disagree = []
    max_logit_diff = 0.0
    max_mirror_diff = 0.0
    max_feat_diff = 0.0
    for i, (body, food, heading) in enumerate(states):
        mode = 1 if i < feat_subset else 0
        enc_hex, action, cpp_logits, cpp_feat = runner.state(
            mode, body, food, heading)
        cpp_bits = np.array([int(t, 16) for t in enc_hex],
                            dtype=np.uint32)
        if not np.array_equal(cpp_bits, enc_bits_ref[i]):
            enc_mismatch += 1
            if enc_mismatch <= 3:
                idx = int(np.nonzero(cpp_bits != enc_bits_ref[i])[0][0])
                print(f"  encoding mismatch state {i} at {idx}")
        for a in range(3):
            d = abs(cpp_logits[a] - float(logits[i][a]))
            if not math.isfinite(d):
                runner.close()
                print("FAIL: nonfinite logit difference")
                return 1
            max_logit_diff = max(max_logit_diff, d)
            max_mirror_diff = max(
                max_mirror_diff,
                abs(cpp_logits[a] - float(mirror[i][a])))
        if action != int(ref_actions[i]):
            action_disagree.append(
                (i, action, int(ref_actions[i]), float(margins[i])))
        if cpp_feat is not None:
            for j, v in enumerate(cpp_feat):
                max_feat_diff = max(max_feat_diff,
                                    abs(v - float(feats[i][j])))
    runner.close()

    mirror_vs_torch = float(np.max(np.abs(logits - mirror)))
    print(f"[{weights_path.name}] states: {n}")
    print(f"  encoding mismatches: {enc_mismatch} / {n}")
    print(f"  max abs logit diff vs NumPy mirror: {max_mirror_diff:.3e}")
    print(f"  max abs logit diff vs PyTorch: {max_logit_diff:.3e}")
    print(f"  (context) mirror vs PyTorch max diff: "
          f"{mirror_vs_torch:.3e}")
    print(f"  action agreement: {n - len(action_disagree)} / {n}")
    for i, ca, ra, margin in action_disagree:
        print(f"    DISAGREE state {i}: native={ca} ref={ra} "
              f"ref_margin={margin:.3e}")
    print(f"  features (first {feat_subset} states): "
          f"max diff={max_feat_diff:.3e}")
    hard_fail, reasons = assess(enc_mismatch, action_disagree,
                                max_mirror_diff)
    for reason in reasons:
        print(f"  FAIL: {reason}")
    return 1 if hard_fail else 0


def run_freeze(out_path: Path, states, fixture_states: int) -> int:
    states = states[:fixture_states]
    fixture = {
        "format": "cnn-parity-v1",
        "description": (
            "Frozen CNN inference parity fixture: harvested Snake "
            "states with NumPy-mirror reference actions and logits "
            "for two committed DA8 checkpoint exports (one plain, "
            "one residual). The mirror is the checkpoint format's "
            "declared parity path (float64 accumulation over the "
            "stored float32 weights); PyTorch agreement is "
            "established by the live check in tools/native_cnn_check.py. "
            "Logits are IEEE754 binary32 values rendered as 8 "
            "lowercase hex digits. The fixture stands outside "
            "native/golden/meta.json's corpus accounting."),
        "regeneration": (
            "Regenerate manually with a torch interpreter: "
            "python tools/native_cnn_check.py --freeze "
            "native/golden/cnn_parity.json (never regenerated by "
            "the test suite)."),
        "checkpoints": [],
    }
    for name in FIXTURE_CHECKPOINTS:
        weights_path = ROOT / "runs" / name
        with open(weights_path) as f:
            doc = json.load(f)
        torch_logits, mirror, _enc, _feats = torch_reference(
            weights_path, states)
        import numpy as np

        entry = {
            "weights": f"runs/{name}",
            "weights_sha256": doc["weights_sha256"],
            "torch_max_logit_diff_at_freeze": float(
                np.max(np.abs(torch_logits - mirror))),
            "states": [],
        }
        for (body, food, heading), row in zip(states, mirror):
            entry["states"].append({
                "body": [list(cell) for cell in body],
                "food": list(food) if food is not None else None,
                "heading": heading,
                "action": int(row.argmax()),
                "logits_hex": [f32_hex(v) for v in row],
            })
        fixture["checkpoints"].append(entry)
        print(f"froze {len(states)} states for {name}")
    with open(out_path, "w") as f:
        json.dump(fixture, f, indent=1, sort_keys=True)
        f.write("\n")
    print(f"wrote {out_path}")
    return 0


def run_frozen(runner_path: str, fixture_path: Path) -> int:
    with open(fixture_path) as f:
        fixture = json.load(f)
    if fixture.get("format") != "cnn-parity-v1":
        print(f"FAIL: unknown fixture format {fixture.get('format')!r}")
        return 1
    rc = 0
    for entry in fixture["checkpoints"]:
        weights_path = ROOT / entry["weights"]
        runner = Runner(runner_path)
        runner.load(str(weights_path))
        states = entry["states"]
        n = len(states)
        disagree = 0
        max_diff = 0.0
        for i, st in enumerate(states):
            body = [tuple(cell) for cell in st["body"]]
            food = tuple(st["food"]) if st["food"] is not None else None
            _enc, action, cpp_logits, _feat = runner.state(
                0, body, food, st["heading"])
            if action != st["action"]:
                disagree += 1
                if disagree <= 3:
                    print(f"  DISAGREE state {i}: native={action} "
                          f"fixture={st['action']}")
            for a in range(3):
                d = abs(cpp_logits[a] - f32_from_hex(st["logits_hex"][a]))
                max_diff = max(max_diff, d)
        runner.close()
        print(f"[{entry['weights']}] frozen states: {n}")
        print(f"  action agreement: {n - disagree} / {n}")
        print(f"  max abs logit diff: {max_diff:.3e} "
              f"(band {LOGIT_BAND:.0e})")
        if disagree:
            print("  FAIL: action disagreements against the fixture")
            rc = 1
        if not math.isfinite(max_diff) or max_diff > LOGIT_BAND:
            print("  FAIL: max logit diff outside the band")
            rc = 1
    print("result: " + ("FAIL" if rc else "PASS"))
    return rc


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runner", required=True)
    ap.add_argument("--weights", default=None,
                    help="single checkpoint (default: all six committed)")
    ap.add_argument("--states", type=int, default=12000)
    ap.add_argument("--feat-subset", type=int, default=500)
    ap.add_argument("--fixture-states", type=int, default=500)
    ap.add_argument("--freeze", default=None,
                    help="write a frozen fixture to this path and exit")
    ap.add_argument("--frozen", default=None,
                    help="replay this frozen fixture and exit")
    args = ap.parse_args()

    if args.frozen:
        return run_frozen(args.runner, Path(args.frozen))

    states = harvest(args.states)
    print(f"harvested {len(states)} states from seeded episodes")
    if args.freeze:
        return run_freeze(Path(args.freeze), states,
                          args.fixture_states)

    names = [Path(args.weights).name] if args.weights else CHECKPOINTS
    rc = 0
    for name in names:
        path = Path(args.weights) if args.weights else ROOT / "runs" / name
        if run_live(args.runner, path, states, args.feat_subset):
            rc = 1
    print("result: " + ("FAIL" if rc else "PASS"))
    return rc


if __name__ == "__main__":
    sys.exit(main())
